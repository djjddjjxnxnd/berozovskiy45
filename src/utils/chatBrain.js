// «ИИ-гид» чата: локальный определитель намерений поверх базы достопримечательностей.
// Работает без интернета и API-ключей — весь интеллект внутри этого файла.
import { monuments } from '../data/monuments';

const PROJECT_PASSWORD = 'школа45';
const AUTHOR_REPLY = 'Проект был создан Паскаловым Александром Дмитриевичем и Его другом';

function normalize(text) {
  return String(text)
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replace(/[^a-zа-я0-9]/gi, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

const has = (norm, words) => words.some((word) => norm.includes(word));

