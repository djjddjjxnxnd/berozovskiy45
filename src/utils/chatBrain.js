function findPlace(norm) {
  for (const [aliases, id] of placeAliases) {
    if (has(norm, aliases)) return monuments.find((m) => m.id === id);
  }
  return null;
}

function placeCard(place, intro) {
  return {
    lines: [
      intro,
      `${place.cardName || place.name}: ${place.shortDesc}`,
      `Адрес: ${place.address}. ${place.status}.`,
    ],
    links: [
      { label: `Подробнее про «${place.cardName || place.name}»`, to: `/monument/${place.id}` },
      { label: 'Показать на карте', to: `/map?id=${place.id}` },
    ],
  };
}

function recommend(ids, intro) {
  const places = ids.map((id) => monuments.find((m) => m.id === id)).filter(Boolean);
  const lines = [intro, ...places.map((p) => `• ${p.cardName || p.name} — ${p.shortDesc.split('.')[0]}.`)];
  return { lines, links: places.map((p) => ({ label: p.cardName || p.name, to: `/monument/${p.id}` })) };
}

export function chatReply(rawText) {
  const norm = normalize(rawText);
  if (!norm) {
    return { lines: ['Напишите вопрос — например: «Куда сходить в выходные?»'] };
  }

  // Пароль проекта
  if (norm.replaceAll(' ', '') === PROJECT_PASSWORD) {
    return { lines: [`🔑 ${AUTHOR_REPLY}`] };
  }
  if (has(norm, ['пароль'])) {
    return { lines: ['Пароль знает только создатель проекта. Если он вам его назвал — просто введите его в чат!'] };
  }

  // Кто автор
  if (has(norm, ['автор', 'кто сделал', 'кто создал', 'создатель', 'кто делал сайт', 'кто сделал сайт', 'чей проект'])) {
    return { lines: ['Имя автора я скажу только тому, кто введёт в чат секретный пароль. Его знает только создатель проекта 😉'] };
  }

  const place = findPlace(norm);
  if (place) {
    return placeCard(place, 'Вот что я знаю об этом месте:');
  }

  if (has(norm, ['привет', 'здравств', 'добрый день', 'добрый вечер', 'доброе утро', 'салют', 'хай', 'ку ']) || norm === 'ку' || norm === 'hi' || norm === 'hello') {
    return {
      lines: ['Привет! Я гид по Берёзовскому — городу первого русского золота.', 'Спросите: «куда сходить», «что посмотреть с детьми» или название любого места — расскажу всё.'],
    };
  }

  if (has(norm, ['с детьми', 'с ребенком', 'с ребёнком', 'дет', 'семей', 'с малыш'])) {
    return recommend([10, 9, 2, 12], 'С детьми в Берёзовском отлично — вот проверенные варианты:');
  }

  if (has(norm, ['музей', 'золот', 'истор', 'шахт'])) {
    return recommend([2, 3, 1, 6], 'Золотая история — наш профиль! Вот с чего начать:');
  }

  if (has(norm, ['зим', 'лыж', 'снег', 'тюбинг', 'ватрушк', 'каток', 'коньк'])) {
    return recommend([12, 10], 'Зимой советую вот это:');
  }

  if (has(norm, ['лет', 'пляж', 'купа', 'загор', 'жарк'])) {
    return recommend([9, 10, 12], 'Летом лучший план такой:');
  }

  if (has(norm, ['природ', 'пруд', 'лес', 'прогул', 'гулять', 'свеж'])) {
    return recommend([9, 10, 31, 32], 'На природе — вот мои любимые места:');
  }

  if (has(norm, ['церков', 'храм', 'мечет', 'собор', 'верующ'])) {
    return recommend([4, 16, 17, 18], 'Духовная сторона города:');
  }

  if (has(norm, ['войн', 'побед', 'геро', 'ветеран', 'мемориал', 'помян'])) {
    return recommend([8, 15, 26, 28], 'Память о подвиге хранят эти места:');
  }

  if (has(norm, ['архитектур', 'дом ', 'старин', 'купец', 'деревянн', 'резьб'])) {
    return recommend([19, 20, 21, 29], 'Старинная архитектура города:');
  }

  if (has(norm, ['малоизвестн', 'тайн', 'необычн', 'спрятан', 'не все знают', 'скрыт'])) {
    return recommend([6, 31, 32, 7], 'Для тех, кто ищет неизведанное:');
  }

  if (has(norm, ['куда сходить', 'куда пойти', 'куда пойти в выходные', 'что посмотреть', 'что посетить', 'посоветуй', 'рекоменд', 'маршрут', 'экскурс', 'выходн'])) {
    return recommend([2, 1, 5, 10, 9], 'Вот классический набор на день в Берёзовском:');
  }

  if (has(norm, ['спасиб', 'благодар', 'круто', 'класс', 'супер'])) {
    return { lines: ['Всегда пожалуйста! Если захотите ещё куда-нибудь сходить — я тут 🙂'] };
  }

  if (has(norm, ['пока', 'до свидан', 'всего добр'])) {
    return { lines: ['До встречи на улицах Берёзовского! Возвращайтесь, если понадобится совет.'] };
  }

  if (has(norm, ['как добраться', 'адрес', 'где наход', 'как найти', 'как доехать'])) {
    return { lines: ['Скажите название места — подскажу адрес и покажу на карте. Например: «Как добраться до Музея золота?»'] };
  }

  return {
    lines: [
      `Я школьный гид по Берёзовскому и знаю в городе ${monuments.length} интересных мест.`,
      'Попробуйте спросить: «куда сходить?», «что посмотреть с детьми?», «расскажи про Музей золота» или название места.',
    ],
    chips: ['Куда сходить?', 'Что посмотреть с детьми?', 'Расскажи про Музей золота'],
  };
}

